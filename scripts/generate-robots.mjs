#!/usr/bin/env node
/**
 * Generates public/robots.txt from lib/md/routes.mjs, so its private paths cannot drift from
 * ai.txt's [scope]. Keep in sync with /llms.txt and /ai.txt (lib/md/site-files.ts).
 *
 * Crawler policy (owner, 2026-10-26):
 *   - AI search and user-fetch bots get the same access as everyone: they decide whether answer
 *     engines can cite Cenner.
 *   - Training crawlers are welcome too, except on freelancer profiles (/freelancer/): those are
 *     people who did not sign up to be in a training set. Search bots can still read and cite them.
 *   - Bytespider is blocked outright: heavy crawling, nothing in return.
 * A bot that has its own group ignores the * group, so every group repeats the private paths.
 *
 * Run: node scripts/generate-robots.mjs
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PRIVATE_PATHS, SITE_URL } from '../lib/md/routes.mjs';

const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../public/robots.txt');

const SEARCH_BOTS = ['OAI-SearchBot', 'ChatGPT-User', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot', 'Perplexity-User'];
const TRAINING_BOTS = ['GPTBot', 'ClaudeBot', 'Google-Extended', 'Applebot-Extended', 'CCBot'];
const BLOCKED_BOTS = ['Bytespider'];

const disallow = (paths) => paths.map((p) => `Disallow: ${p}`).join('\n');
const group = (agents, body) => `${agents.map((a) => `User-agent: ${a}`).join('\n')}\n${body}`;

const txt = `# Cenner — Freelance Platforma Hrvatska
# ${SITE_URL}
# Generated by scripts/generate-robots.mjs; edit that, not this file.
# Keep in sync with ${SITE_URL}/llms.txt and ${SITE_URL}/ai.txt.

${group(['*'], `Allow: /\n\n# Private / authenticated pages — do not index\n${disallow(PRIVATE_PATHS)}`)}

# AI search and user-fetch crawlers: everything public, so Cenner can be cited.
${group(SEARCH_BOTS, `Allow: /\n${disallow(PRIVATE_PATHS)}`)}

# AI training crawlers: everything public except freelancer profiles.
${group(TRAINING_BOTS, `Allow: /\n${disallow([...PRIVATE_PATHS, '/freelancer/'])}`)}

${group(BLOCKED_BOTS, 'Disallow: /')}

# Plain-text summary for AI tools: ${SITE_URL}/llms.txt
# Usage policy for AI systems: ${SITE_URL}/ai.txt

Sitemap: ${SITE_URL}/sitemap.xml
Sitemap: https://api.cenner.hr/sitemap-dynamic.xml
`;

writeFileSync(OUTPUT, txt, 'utf8');
console.log(`[robots] Written ${OUTPUT}`);
