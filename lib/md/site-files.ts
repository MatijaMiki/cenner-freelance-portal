/**
 * /llms.txt, /llms-full.txt, /ai.txt and /api/md/_catalog, generated per request (and cached at the
 * edge) from the renderer registry, so a page added there shows up in all four.
 *
 * Keep in sync: robots.txt (scripts/generate-robots.mjs), llms.txt and ai.txt all take their
 * private paths from PRIVATE_PATHS in lib/md/routes.mjs and their identity from SITE below.
 */
import { COMPANY, companyAddress } from '../company';
import { priceItem } from '../cjenik.js';
import { LLMS_SECTIONS, MD_ROUTES, PRIVATE_PATHS, SITE_URL, mdPathOf } from './routes.mjs';
import { listMarkdownRoutes, renderMarkdownPath, type CatalogEntry } from './registry';
import { abs, clean, eur, renderPage } from './format';

/** Who Cenner is, for every machine-readable file. Same facts as the Organization JSON-LD in index.html. */
export const SITE = {
  name: COMPANY.brand,
  url: SITE_URL,
  description:
    "Cenner (cenner.hr) is a Croatian freelance marketplace and an in-house web studio, based in Zagreb. Businesses find identity-verified Croatian freelancers for websites, design, marketing and programming, buy fixed-price packages, and the freelancer is paid only after the work is delivered. Cenner's own team also builds websites, WordPress sites, web apps, CRM systems and automations at a fixed price.",
  descriptionHr:
    'Cenner je hrvatska freelance platforma (freelance Hrvatska, honorarni posao, izrada web stranica) i vlastiti studio za web stranice, aplikacije i automatizacije.',
  email: COMPANY.email,
  supportEmail: COMPANY.supportEmail,
};

const pct = (id: string) => `${priceItem(id).price}%`;

function keyFacts(): string {
  return [
    `Founded ${COMPANY.founded} in ${COMPANY.city}, Croatia, by ${COMPANY.owner} (${COMPANY.legalName}, MB ${COMPANY.mb}, ${companyAddress}).`,
    `Freelancer plans: Free, Pro ${eur(priceItem('plan-pro').price)}/month, Ultra ${eur(priceItem('plan-ultra').price)}/month, Enterprise ${eur(priceItem('plan-enterprise').price)}/month; Cenner's commission per delivered project is ${pct('commission-free')}, ${pct('commission-pro')}, ${pct('commission-ultra')} and ${pct('commission-enterprise')} respectively. Buyers pay a ${pct('buyer-fee')} service fee.`,
    `Studio starting prices: websites from ${eur(priceItem('studio-web-stranice').price)}, WordPress from ${eur(priceItem('studio-wordpress').price)}, graphic design from ${eur(priceItem('studio-dizajn').price)}.`,
    `Every freelancer passes KYC identity verification; payments run through Stripe and are released after delivery. Site language: Croatian.`,
    `Contact: ${SITE.email}, support ${SITE.supportEmail}.`,
  ].join(' ');
}

const SECTION_TITLES: Record<string, string> = {
  core: 'Core pages',
  marketplace: 'Marketplace landing pages (usluge, freelanceri)',
  guides: 'Guides (blog)',
  listings: 'Service listings',
  legal: 'Optional',
};

/** How many service listings llms.txt and llms-full.txt carry; the Marketplace page lists the rest. */
const LISTING_CAP = 50;

function bySection(entries: CatalogEntry[]): Record<string, CatalogEntry[]> {
  const out: Record<string, CatalogEntry[]> = {};
  for (const s of LLMS_SECTIONS) out[s] = [];
  for (const e of entries) if (e.section && out[e.section]) out[e.section].push(e);
  out.listings = out.listings.slice(0, LISTING_CAP);
  return out;
}

const today = () => new Date().toISOString().slice(0, 10);

export async function llmsTxt(): Promise<string> {
  const sections = bySection(await listMarkdownRoutes());
  const lines = (es: CatalogEntry[]) => es.map((e) => `- [${clean(e.title)}](${abs(e.md)}): ${clean(e.summary)}`).join('\n');
  const parts = [
    `# ${SITE.name}`,
    `> ${SITE.description}`,
    `${SITE.descriptionHr}\n\n${keyFacts()}`,
    '<!-- Generated by lib/md/site-files.ts. Keep in sync with /robots.txt and /ai.txt. -->',
  ];
  for (const s of LLMS_SECTIONS) {
    if (s === 'legal') continue;
    if (!sections[s].length) continue;
    let block = `## ${SECTION_TITLES[s]}\n\n${lines(sections[s])}`;
    if (s === 'listings') block += `\n- [All listings](${abs(mdPathOf('/marketplace'))}): the Marketplace page lists every current service.`;
    parts.push(block);
  }
  parts.push(
    `## Machine-readable\n\n` +
      [
        `- [Full content](${SITE_URL}/llms-full.txt): every page above in one file`,
        `- [Markdown catalog](${SITE_URL}/api/md/_catalog): every markdown route as JSON`,
        `- [Sitemap](${SITE_URL}/sitemap.xml)`,
        `- [AI usage policy](${SITE_URL}/ai.txt)`,
      ].join('\n'),
  );
  if (sections.legal.length) parts.push(`## Optional\n\n${lines(sections.legal)}`);
  return parts.join('\n\n') + '\n';
}

/** Soft ceiling from the llms-full convention; over it we still serve, but say so in the log. */
const FULL_WARN_CHARS = 500_000;

export async function llmsFullTxt(): Promise<string> {
  const sections = bySection(await listMarkdownRoutes());
  const parts = [
    `# ${SITE.name} - full content\n> ${SITE.description}\nGenerated: ${today()}\n\nService listings are capped at ${LISTING_CAP}; freelancer profiles are not included. The complete list of pages is at ${SITE_URL}/api/md/_catalog.`,
  ];
  for (const s of LLMS_SECTIONS) {
    for (const e of sections[s]) {
      try {
        const page = await renderMarkdownPath(e.path);
        if (page) parts.push(`---\n<!-- source: ${abs(e.path)} -->\n${renderPage(page)}`);
      } catch (err) {
        console.warn(`[md] llms-full: ${e.path} skipped:`, (err as Error).message);
      }
    }
  }
  const out = parts.join('\n\n');
  if (out.length > FULL_WARN_CHARS) console.warn(`[md] llms-full.txt is ${out.length} chars (> ${FULL_WARN_CHARS})`);
  return out;
}

export function aiTxt(): string {
  const included = MD_ROUTES.map((r) => r.path.replace(/:[a-z]+/gi, '*'));
  return [
    '# ai.txt for cenner.hr (ai-txt spec v1.1.1, ai-visibility.org.uk)',
    '# Generated by lib/md/site-files.ts. Keep in sync with /robots.txt and /llms.txt.',
    '',
    '[identity]',
    `name: ${SITE.name}`,
    `legal-name: ${COMPANY.legalName}`,
    `url: ${SITE.url}`,
    `description: ${SITE.description}`,
    `contact: ${SITE.email}`,
    '',
    '[permissions]',
    'summarise: allowed',
    'quote: allowed, with attribution',
    'cite: allowed',
    'index: allowed, for search and answer engines',
    '',
    '[restrictions]',
    '- Do not fabricate quotes, prices, statistics or claims and attribute them to Cenner.',
    '- Do not invent reviews or ratings for Cenner, its freelancers or its clients.',
    "- Do not present Cenner's content as your own.",
    '- Do not train on personal or user-generated content: freelancer profiles (/freelancer/*), community posts, messages, orders and contracts.',
    '- Prices and fees change; quote them with the date and link to the page they came from.',
    '',
    '[attribution]',
    `format: "${SITE.name} (cenner.hr)" with the canonical HTML URL of the page, e.g. ${SITE_URL}/subscription`,
    'link-to: the HTML page, not its .md version',
    '',
    '[scope]',
    `include: ${included.join(', ')}`,
    `exclude: ${[...PRIVATE_PATHS, '/auth', '/api/render'].join(', ')}`,
    '',
    '[contact]',
    `email: ${SITE.email}`,
    `support: ${SITE.supportEmail}`,
    '',
    `Last updated: ${today()}`,
    '',
  ].join('\n');
}

export async function catalogJson(): Promise<string> {
  const routes = await listMarkdownRoutes();
  return (
    JSON.stringify(
      {
        site: SITE.url,
        generated: today(),
        count: routes.length,
        routes: routes.map((r) => ({ path: r.path, url: abs(r.path), md: abs(r.md), title: r.title, summary: r.summary })),
        // Addressable as markdown but not enumerated here.
        patterns: [`${SITE_URL}/freelancer/{id}.md`],
      },
      null,
      2,
    ) + '\n'
  );
}
